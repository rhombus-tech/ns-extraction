"""Check Theorem (traceless strain attenuation) on the periodic box and probe how sharp it is.

|int w.S[w'].w| <= (1/sqrt3) ||w||_4^2 ||w'||_2, with S = sym grad of the velocity generated by w'.
"""
import sys
import numpy as np
from scipy.optimize import minimize
from spectral import Grid, random_vorticity

BOUND = 1 / np.sqrt(3)
N = 16


def quantities(g, w, wp):
    s = g.strain_from_vorticity(wp)
    ws = np.einsum("i...,ij...,j...->...", w, s, w)
    num = abs(g.integrate(ws))
    n4sq = np.sqrt(g.integrate(np.sum(w * w, axis=0) ** 2))
    n2 = np.sqrt(g.integrate(np.sum(wp * wp, axis=0)))
    return num / (n4sq * n2), s


def pointwise_checks(g, rng):
    w = random_vorticity(g, rng, kmax=3.0)
    s = g.strain_from_vorticity(w)
    tr = np.max(np.abs(np.einsum("ii...->...", s)))
    fro2 = g.integrate(np.einsum("ij...,ij...->...", s, s))
    half = 0.5 * g.integrate(np.sum(w * w, axis=0))
    ev = np.linalg.eigvalsh(np.moveaxis(s, (0, 1), (-2, -1)))
    ratio = np.max(ev[..., -1] ** 2 / np.maximum(np.einsum("ij...,ij...->...", s, s), 1e-300))
    return tr, abs(fro2 - half) / half, ratio


MODES = [(a, b, c) for a in (-1, 0, 1) for b in (-1, 0, 1) for c in (-1, 0, 1) if (a, b, c) != (0, 0, 0)]


def field_from_params(g, p):
    ah = np.zeros((3, g.n, g.n, g.n), dtype=complex)
    m = len(MODES)
    c = p[: 3 * m] + 1j * p[3 * m: 6 * m]
    for comp in range(3):
        for idx, (a, b, cc) in enumerate(MODES):
            ah[comp, a % g.n, b % g.n, cc % g.n] = c[comp * m + idx]
    a = g.ifft(ah)
    return g.curl(a)


def optimise(g, rng, tie, iters=40):
    m = 6 * len(MODES)
    x0 = rng.standard_normal(m if tie else 2 * m)

    def f(p):
        w = field_from_params(g, p[:m])
        wp = w if tie else field_from_params(g, p[m:])
        r, _ = quantities(g, w, wp)
        return -r

    res = minimize(f, x0, method="L-BFGS-B", options={"maxiter": iters, "maxfun": 40000})
    return -res.fun


def main():
    g = Grid(N)
    rng = np.random.default_rng(1)
    ok = True

    tr, fro_err, lam = pointwise_checks(g, rng)
    good = tr < 1e-10 and fro_err < 1e-10 and lam <= 2 / 3 + 1e-12
    ok &= good
    print(f"tr S max = {tr:.2e}; | ||S||_F^2 - ||w||^2/2 |/(||w||^2/2) = {fro_err:.2e}; "
          f"max lambda_max^2/|S|_F^2 = {lam:.4f} (<= 2/3 = {2/3:.4f}) {'PASS' if good else 'FAIL'}")

    worst = 0.0
    for _ in range(300):
        w = random_vorticity(g, rng, kmax=2.5)
        wp = random_vorticity(g, rng, kmax=2.5)
        r1, _ = quantities(g, w, wp)
        r2, _ = quantities(g, w, w)
        worst = max(worst, r1, r2)
    good = worst <= BOUND
    ok &= good
    print(f"random fields (300 x 2): max ratio = {worst:.4f}  bound 1/sqrt3 = {BOUND:.4f} {'PASS' if good else 'FAIL'}")

    for tie, label in ((True, "w' = w (self-induced strain)"), (False, "w' independent of w")):
        best = max(optimise(g, rng, tie) for _ in range(2))
        good = best <= BOUND + 1e-9
        ok &= good
        print(f"optimised, {label}: best ratio = {best:.4f}  ({best/BOUND:.0%} of bound) {'PASS' if good else 'FAIL'}")
    print("ALL PASS" if ok else "FAILURES")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
